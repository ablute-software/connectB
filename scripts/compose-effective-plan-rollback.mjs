// Prompt 914 — composes scripts/rollback-effective-plan-914.sql: how to put the two wallet functions back EXACTLY as production had them
// before migration 20261013170000_effective_plan.sql, should the migration ever have to be undone.
//
// It is DERIVED from the migration, never typed: the migration's two function bodies minus the "Prompt 914" blocks and minus the column
// qualification are, byte for byte, production's old text (the rehearsal's A1 check proves it against pg_get_functiondef), so removing
// them again is the rollback. A test (effective-plan-rehearsal.test.ts) fails when the committed script is not what this produces.
//
//   node scripts/compose-effective-plan-rollback.mjs            writes scripts/rollback-effective-plan-914.sql
//   node scripts/compose-effective-plan-rollback.mjs --stdout   prints it (what the drift test compares against)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const norm = (t) => t.replace(/\r\n/g, '\n');

export function composeRollback() {
  const migration = norm(fs.readFileSync(path.join(root, 'supabase/migrations/20261013170000_effective_plan.sql'), 'utf8'));
  const from = migration.indexOf('create or replace function public.ai_wallet_status');
  const to = migration.indexOf('-- 3. who may call it');
  if (from < 0 || to < 0) throw new Error('migration layout changed: cannot find the two wallet functions');
  const bodies = migration.slice(from, to)
    .replace(/\n  -- >>> Prompt 914[\s\S]*?-- <<< Prompt 914\n/g, '')
    .replace('(orgs.is_test or orgs.is_internal)', '(is_test or is_internal)')
    .trimEnd();
  return `-- Prompt 914 — ROLLBACK of migration 20261013170000_effective_plan.sql. NOT to be run unless that migration has to be undone.
--
-- GENERATED by scripts/compose-effective-plan-rollback.mjs from the migration itself (its two wallet functions minus the "Prompt 914"
-- blocks and minus the column qualification = production's text before the migration, proved by the rehearsal's A1 check); a test
-- fails if this file diverges. Both functions are CREATE OR REPLACE, so their grants are kept.
--
-- WHAT UNDOING IT MEANS: the AI wallet goes back to reading orgs.plan (an org on a free trial is "Elementary" again: Wisify and Insignals
-- 500 -> 80), AND ai_wallet_status() goes back to raising 42702 on every call (the credits card of /api/me hidden again), which is how
-- production was before. If only the plan rule has to go, keep the qualification: edit it back by hand.
--
-- effective_plan() is dropped LAST: nothing that is left references it.

${bodies}

drop function if exists public.effective_plan(uuid);
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = composeRollback();
  if (process.argv.includes('--stdout')) process.stdout.write(out);
  else { fs.writeFileSync(path.join(root, 'scripts/rollback-effective-plan-914.sql'), out); console.log(`scripts/rollback-effective-plan-914.sql — ${out.split('\n').length} lines`); }
}
